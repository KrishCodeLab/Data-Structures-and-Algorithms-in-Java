public class Loops_SquarePattern {
  public static void main(String[] args) {
    // print square pattern
    int count = 0;

    while (count <= 4) {
      System.out.println("* * * * ");
      count++;
    }
    System.out.println();
    System.out.println();
    System.out.println();

    for (int i = 0; i <= 4; i++) {
      System.out.println("* * * * ");

    }
  }
}
